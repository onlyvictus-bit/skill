#!/usr/bin/env python3
"""M5: per-unit results with mechanical excerpts, reconciliation, export.

Every result carries its original excerpt attached deterministically from
the frozen source — never regenerated by a model, so transcription loss is
impossible by construction. Reconciliation is exact set arithmetic over
unit IDs; uniform (copy-pasted) interpretations are flagged, never trusted.
Synthesis manifests map every retained claim to units and every required
unit to a claim. Exports are source-ordered JSONL plus a claim index.
"""
import hashlib
import json
from pathlib import Path

RESULT_KEYS = {"schema_version", "unit_id", "source_digest", "attempt_id",
               "original_excerpt", "excerpt_sha256", "interpretation",
               "findings", "disposition", "task_digest"}
DISPOSITIONS = ("resolved", "unresolved")


class ResultError(ValueError):
    pass


def attach_excerpt(source_bytes, manifest, unit_id):
    table = {u["id"]: u for u in manifest.get("units", [])}
    unit = table.get(unit_id)
    if unit is None:
        raise ResultError("E_RESULT_UNIT: unknown unit %r" % (unit_id,))
    start, end = unit["range"]
    excerpt = source_bytes[start:end].decode("utf-8")
    return excerpt, hashlib.sha256(excerpt.encode("utf-8")).hexdigest()


def make_result(source_bytes, manifest, unit_id, task_digest, attempt_id,
                interpretation, findings=(), disposition="resolved"):
    excerpt, digest = attach_excerpt(source_bytes, manifest, unit_id)
    if not isinstance(interpretation, str) or not interpretation.strip():
        raise ResultError("E_RESULT_EMPTY: unit %s has no interpretation" % (unit_id,))
    if disposition not in DISPOSITIONS:
        raise ResultError("E_RESULT_DISPOSITION: %r" % (disposition,))
    return {"schema_version": 2, "unit_id": unit_id,
            "source_digest": manifest["source_digest"], "attempt_id": attempt_id,
            "original_excerpt": excerpt, "excerpt_sha256": digest,
            "interpretation": interpretation, "findings": list(findings),
            "disposition": disposition, "task_digest": task_digest}


def validate_result(record, source_bytes, manifest, *, expect_task_digest=None,
                    expect_attempt_id=None):
    if not isinstance(record, dict):
        return ["E_RESULT_TYPE: record must be an object"]
    unknown = sorted(set(record) - RESULT_KEYS)
    if unknown:
        return ["E_SCHEMA_FIELD: unsupported field(s) %s" % (",".join(unknown))]
    missing = sorted(RESULT_KEYS - set(record))
    if missing:
        return ["E_SCHEMA_REQUIRED: missing %s" % (",".join(missing))]
    if record.get("schema_version") != 2:
        return ["E_SCHEMA_VERSION: result schema must be 2"]
    if not isinstance(record.get("unit_id"), str) or not record["unit_id"].strip():
        return ["E_RESULT_UNIT: unit_id must be a non-empty string"]
    if not isinstance(record.get("interpretation"), str) or not record["interpretation"].strip():
        return ["E_RESULT_EMPTY: interpretation must be non-empty text"]
    if not isinstance(record.get("findings"), list):
        return ["E_RESULT_FINDINGS: findings must be a list"]
    if record.get("disposition") not in DISPOSITIONS:
        return ["E_RESULT_DISPOSITION: disposition must be one of %s" % (sorted(DISPOSITIONS),)]
    for key in ("task_digest", "attempt_id"):
        if not isinstance(record.get(key), str) or not record[key].strip():
            return ["E_RESULT_BASIS: %s must be a non-empty string" % (key,)]
    try:
        excerpt, digest = attach_excerpt(source_bytes, manifest, record.get("unit_id"))
    except ResultError as exc:
        return [str(exc)]
    if record.get("original_excerpt") != excerpt or record.get("excerpt_sha256") != digest:
        return ["E_RESULT_EXCERPT: excerpt does not match frozen source"]
    if record.get("source_digest") != manifest.get("source_digest"):
        return ["E_RESULT_STALE: result bound to another source version"]
    if expect_task_digest is not None and record.get("task_digest") != expect_task_digest:
        return ["E_RESULT_TASK: result task does not bind the accepted task"]
    if expect_attempt_id is not None and record.get("attempt_id") != expect_attempt_id:
        return ["E_RESULT_ATTEMPT: result attempt does not bind the accepted attempt"]
    return []


def validate_rich_results(records, source_bytes, manifest, task_digest, attempt_id,
                          expected_ids=None):
    """Validate persisted rich records bound to one accepted attempt."""
    if not isinstance(records, list) or not records:
        return False, ["E_RICH_RESULTS_EMPTY: one or more rich result records are required"]
    expected = list(expected_ids if expected_ids is not None else
                    [unit["id"] for unit in manifest.get("units", [])])
    errors = []
    for record in records:
        if not isinstance(record, dict):
            errors.append("E_RICH_RESULTS_TYPE: every result must be an object")
            continue
        errors.extend(validate_result(record, source_bytes, manifest,
                                      expect_task_digest=task_digest,
                                      expect_attempt_id=attempt_id))
    reconciliation = reconcile(expected, [record for record in records if isinstance(record, dict)])
    if not reconciliation["complete"]:
        errors.append("E_RICH_RESULTS_IDS: missing=%s duplicates=%s foreign=%s" %
                      (reconciliation["missing"], reconciliation["duplicates"],
                       reconciliation["foreign"]))
    return not errors, errors


def reconcile(expected_ids, records):
    """Exact ID arithmetic. Returns dict with missing/duplicates/foreign/uniform."""
    seen, dupes, foreign = set(), set(), set()
    expected = set(expected_ids)
    for record in records:
        ident = record.get("unit_id")
        if ident in seen:
            dupes.add(ident)
        seen.add(ident)
        if ident not in expected:
            foreign.add(ident)
    missing = sorted(expected - seen)
    by_text = {}
    for record in records:
        by_text.setdefault(record.get("interpretation", ""), []).append(record.get("unit_id"))
    uniform = sorted(i for ids in by_text.values() if len(ids) > 1 for i in ids)
    return {"missing": missing, "duplicates": sorted(dupes), "foreign": sorted(foreign),
            "uniform": uniform,
            "complete": not missing and not dupes and not foreign}


def export_jsonl(records_by_ordinal, path):
    """Source-ordered JSONL. One line per record, no more, no less."""
    lines = [json.dumps(r, sort_keys=True, ensure_ascii=False) for r in records_by_ordinal]
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(lines)


def verify_export(path, expected_ids, source_bytes, manifest):
    records = [json.loads(line) for line in
               Path(path).read_text(encoding="utf-8").splitlines() if line.strip()]
    rec = reconcile(expected_ids, records)
    errors = []
    if not rec["complete"]:
        errors.append("E_EXPORT_IDS: missing=%s duplicates=%s foreign=%s"
                      % (rec["missing"], rec["duplicates"], rec["foreign"]))
    for record in records:
        errors.extend(validate_result(record, source_bytes, manifest))
    return errors


def validate_synthesis(claims, expected_ids, require_full=True):
    """Every claim maps to known units; every required unit is claimed."""
    if not isinstance(claims, list):
        return ["E_SYNTHESIS_TYPE: claims must be a list"]
    expected = set(expected_ids)
    covered, errors = set(), []
    for idx, claim in enumerate(claims):
        if not isinstance(claim, dict):
            errors.append("E_SYNTHESIS_TYPE: claim %d not an object" % (idx,))
            continue
        units = claim.get("unit_ids", [])
        if not isinstance(units, list) or not units:
            errors.append("E_SYNTHESIS_UNMAPPED: claim %d has no units" % (idx,))
            continue
        for ident in units:
            if ident not in expected:
                errors.append("E_SYNTHESIS_FOREIGN: claim %d cites %s" % (idx, ident))
            covered.add(ident)
    if require_full:
        missing = sorted(expected - covered)
        if missing:
            errors.append("E_SYNTHESIS_GAP: units without claims: %s" % (",".join(missing)))
    return errors
